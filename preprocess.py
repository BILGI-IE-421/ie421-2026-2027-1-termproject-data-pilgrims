"""Clean, reshape and join the raw data for the three research questions.

Run from the repository root after scripts/download_data.py:
    python scripts/preprocess.py

RQ1  Brent change vs. change in Big Mac gaps, high-volatility vs. calm periods
     -> brent_logchg_since_prev, USD_raw_chg, oil_regime
RQ2  Is that relationship stable over 2000-2025?            -> date (edition)
RQ3  Exporter/importer share of the cross-country spread,
     and does it grow when oil is expensive?                -> USD_raw, oil_role, brent_avg_30d

Inputs (data/raw/, not committed)      Outputs (data/*.csv and data/json/*.json, committed)
big-mac-full-index.csv                 bigmac_clean      one row per economy and edition
big-mac-source-data-v2.csv (check)     brent_daily       one row per trading day
RBRTEd.xls           ei_oil_balance    one row per economy and year
EI-Stats-Review-ALL-data*.xlsx         merged_dataset    canonical analysis table (economy x edition)
                                       cleaning_report.md  numbers behind every decision

Three explicit Energy Institute paths are available:
  Default: require an original all-data workbook.
  --allow-ei-snapshot: reuse the historical 1965–2025 processed snapshot, with disclosure.
  --ei-source pdf: use only the published 2015–2025 PDF-extracted oil tables;
                   non-reported production and older years remain missing.
All outputs include CSV and JSON forms; the merged_dataset is the single canonical analysis table.
"""

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "data"
JSON_OUT = OUT / "json"

DAYFIRST = False  # one date convention for the whole project: ISO dates, never day-first
REPORT: list[str] = ["# Cleaning report", "", "Generated by `python scripts/preprocess.py`.", ""]


def log(line: str = "") -> None:
    """Print a line and keep it for data/cleaning_report.md."""
    print(line)
    REPORT.append(line)


def parse_dates(values: pd.Series, fmt: str | None = None) -> pd.Series:
    """The single date parser of the project; unparseable values become NaT and are counted."""
    parsed = pd.to_datetime(values, format=fmt, dayfirst=DAYFIRST, errors="coerce")
    n_bad = int(parsed.isna().sum() - values.isna().sum())
    if n_bad:
        log(f"- WARNING: {n_bad} dates could not be parsed")
    return parsed


# 1. Big Mac index ----------------------------------------------------------------------------
def clean_bigmac() -> pd.DataFrame:
    log("## 1. Big Mac index (The Economist, big-mac-full-index.csv)")
    df = pd.read_csv(RAW / "big-mac-full-index.csv", dtype={"iso_a3": str, "currency_code": str, "name": str})
    version = RAW / "big-mac-version.json"
    if version.exists():
        meta = json.loads(version.read_text()).get("big-mac-full-index.csv", {})
        log(f"- version: blob sha {meta.get('sha', 'n/a')}, accessed {meta.get('accessed')}, via {meta.get('via')}")
    log(f"- raw: {df.shape[0]} rows x {df.shape[1]} columns")
    log("- units: local_price in local currency; dollar_ex = local currency per US dollar; USD_raw = "
        "dollar price / US price - 1 (0.10 = Big Mac 10% dearer than in the US). Dates are edition dates "
        "(calendar day, no time of day, so no time zone)")
    df["date"] = parse_dates(df["date"], "%Y-%m-%d")

    n_dup = int(df.duplicated(["iso_a3", "date"]).sum())
    df = df.drop_duplicates(["iso_a3", "date"], keep="last")
    log(f"- duplicate (iso_a3, date) rows removed: {n_dup}")

    # The source spells one country two ways ('UAE', 'United Arab Emirates'): keep the latest name.
    latest = df.sort_values("date").groupby("iso_a3")["name"].last()
    log(f"- names harmonised: {sorted(df.loc[df['name'] != df['iso_a3'].map(latest), 'name'].unique())}")
    df["name"] = df["iso_a3"].map(latest)

    n_off = int((np.abs(df["local_price"] / df["dollar_ex"] / df["dollar_price"] - 1) > 0.01).sum())
    log(f"- rows where dollar_price != local_price / dollar_ex (>1%): {n_off}")

    # Gaps above 100% are real (e.g. Venezuela, Switzerland), so they are flagged, not dropped.
    df["flag_extreme_raw"] = df["USD_raw"].abs() > 1
    log(f"- |USD_raw| > 100% flagged, kept: {int(df['flag_extreme_raw'].sum())} rows "
        f"{sorted(df.loc[df['flag_extreme_raw'], 'iso_a3'].unique())}")

    size = df.groupby("date").size()
    log(f"- {df['date'].nunique()} editions {df['date'].min():%Y-%m-%d} to {df['date'].max():%Y-%m-%d} "
        f"(annual until 2005, then twice a year); {size.min()}-{size.max()} economies per edition, "
        f"{df['iso_a3'].nunique()} in total")
    log("- kept: raw USD index and its inputs; GDP-adjusted and EUR/GBP/JPY/CNY indices dropped (not in RQs)")

    cross_check_source(df)
    cols = ["date", "iso_a3", "name", "currency_code", "local_price", "dollar_ex", "dollar_price",
            "USD_raw", "flag_extreme_raw"]
    return df[cols].sort_values(["date", "iso_a3"]).reset_index(drop=True)


def cross_check_source(index_df: pd.DataFrame) -> None:
    """Explain the rows that exist in the source data but not in the published index."""
    path = RAW / "big-mac-source-data-v2.csv"
    if not path.exists():
        return
    src = pd.read_csv(path, dtype={"iso_a3": str, "currency_code": str})
    src["date"] = parse_dates(src["date"], "%Y-%m-%d")
    extra = src.merge(index_df[["iso_a3", "date"]], on=["iso_a3", "date"], how="left", indicator=True)
    extra = extra[extra["_merge"] == "left_only"]
    log(f"- cross-check: source data {len(src)} rows, index {len(index_df)}; {len(extra)} extra source rows "
        f"by currency {extra['currency_code'].value_counts().to_dict()} -> euro members are one 'Euro area' "
        f"(EUZ) row in the index (one exchange rate), so the index file is used")


# 2. Brent ------------------------------------------------------------------------------------
def clean_brent() -> pd.DataFrame:
    log("\n## 2. Brent spot price, daily (EIA series RBRTE)")
    eia = RAW / "RBRTEd.xls"
    if not eia.exists():
        raise FileNotFoundError(
            "EIA Brent file missing: data/raw/RBRTEd.xls. "
            "Run python scripts/download_data.py first."
        )
    df = pd.read_excel(eia, sheet_name="Data 1", skiprows=2)
    df.columns = ["date", "brent_usd"]
    df["date"] = parse_dates(df["date"])
    log(f"- file: {eia.name}; raw rows: {len(df)}")
    df["brent_usd"] = pd.to_numeric(df["brent_usd"], errors="coerce")
    n_raw = len(df)
    df = df.dropna().drop_duplicates("date", keep="last")
    df = df[df["brent_usd"] > 0].sort_values("date").reset_index(drop=True)
    gaps = df["date"].diff().dt.days
    log(f"- removed {n_raw - len(df)} rows (missing price, duplicate date or non-positive price)")
    log(f"- clean: {len(df)} trading days, {df['date'].min():%Y-%m-%d} to {df['date'].max():%Y-%m-%d}")
    log("- units: US dollars per barrel, free on board; one price per London trading day (calendar date, "
        "no time of day), so dates are compared with edition dates as plain days, no time-zone conversion")
    log(f"- gaps over 5 calendar days: {int((gaps > 5).sum())} (longest {int(gaps.max())}, mostly 1993-2006); "
        f"not filled, every edition window still contains data")
    return df


